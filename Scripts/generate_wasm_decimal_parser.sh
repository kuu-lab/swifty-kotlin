#!/usr/bin/env bash
# Regenerates Sources/CompilerBackend/Wasm/WasmDecimalParserBody.swift from
# Scripts/wasm_decimal_parse.c. The generated artifact is committed so normal
# compiler builds do not need a wasm-targeting Clang.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
CLANG_BIN="${CLANG:-clang}"
TMP_DIR="$(mktemp -d)"
trap 'rm -rf "$TMP_DIR"' EXIT

"$CLANG_BIN" \
  --target=wasm32-unknown-unknown-wasm \
  -O3 -nostdlib -ffreestanding -fno-builtin \
  -Wl,--no-entry -Wl,--export=parse_exact_fp \
  "$ROOT/Scripts/wasm_decimal_parse.c" \
  -o "$TMP_DIR/decimal_parse.wasm"

CLANG_PATH="$(command -v "$CLANG_BIN" || true)"
LLVM_OBJDUMP="${LLVM_OBJDUMP:-}"
if [[ -z "$LLVM_OBJDUMP" && -n "$CLANG_PATH" && -x "$(dirname "$CLANG_PATH")/llvm-objdump" ]]; then
  LLVM_OBJDUMP="$(dirname "$CLANG_PATH")/llvm-objdump"
fi
if [[ -z "$LLVM_OBJDUMP" ]]; then
  LLVM_OBJDUMP="$(command -v llvm-objdump || true)"
fi
if [[ -z "$LLVM_OBJDUMP" ]]; then
  echo "llvm-objdump is required to validate the generated parser body" >&2
  exit 1
fi
if ! DISASSEMBLY="$("$LLVM_OBJDUMP" -d "$TMP_DIR/decimal_parse.wasm" 2>/dev/null)"; then
  echo "llvm-objdump failed; refusing to emit an unvalidated parser body" >&2
  exit 1
fi
if grep -Eq '^[[:space:]]+[0-9a-f]+:([[:space:]][0-9a-f]{2})+[[:space:]]+call[[:space:]]' <<<"$DISASSEMBLY"; then
  echo "generated function contains a direct call; force-inlining failed" >&2
  exit 1
fi
if grep -Eq '^[[:space:]]+[0-9a-f]+:([[:space:]][0-9a-f]{2})+[[:space:]]+global\.(get|set)[[:space:]]' <<<"$DISASSEMBLY"; then
  echo "generated function references wasm globals; refusing external state" >&2
  exit 1
fi

python3 - "$TMP_DIR/decimal_parse.wasm" "$ROOT/Sources/CompilerBackend/Wasm/WasmDecimalParserBody.swift" <<'PY'
import sys

wasm_path, out_path = sys.argv[1], sys.argv[2]
data = open(wasm_path, "rb").read()

def read_uleb(pos):
    result = 0
    shift = 0
    while True:
        byte = data[pos]
        pos += 1
        result |= (byte & 0x7F) << shift
        if byte < 0x80:
            return result, pos
        shift += 7

pos = 8
bodies = []
while pos < len(data):
    section_id = data[pos]
    pos += 1
    section_size, pos = read_uleb(pos)
    if section_id == 2:
        count, _ = read_uleb(pos)
        if count:
            raise SystemExit("generated parser module has import entries; refusing external state")
    if section_id == 10:
        cursor = pos
        count, cursor = read_uleb(cursor)
        for _ in range(count):
            body_size, cursor = read_uleb(cursor)
            bodies.append(data[cursor:cursor + body_size])
            cursor += body_size
    pos += section_size

if len(bodies) != 1:
    raise SystemExit(f"expected exactly one generated wasm function, got {len(bodies)}")
body = bodies[0]
if not body or body[-1] != 0x0B:
    raise SystemExit("generated function body does not end in wasm end opcode")

lines = [
    "// Generated by Scripts/generate_wasm_decimal_parser.sh; do not edit by hand.",
    "// Source: Scripts/wasm_decimal_parse.c",
    "enum WasmDecimalParserBody {",
    "    static let bytes: [UInt8] = [",
]
for offset in range(0, len(body), 16):
    chunk = body[offset:offset + 16]
    lines.append("        " + ", ".join(f"0x{byte:02X}" for byte in chunk) + ",")
lines += [
    "    ]",
    "}",
    "",
]
open(out_path, "w").write("\n".join(lines))
print(f"wrote {out_path}: {len(body)} byte wasm function body")
PY
