fun main() {
    println(Double.NaN.toInt())
    println(Double.POSITIVE_INFINITY.toLong())
    println((-0.5).toInt())
    println(3.99.toInt())
    println((-3.99).toLong())
    println(Float.NaN.toInt())
    println(Float.POSITIVE_INFINITY.toLong())
    println((-0.5f).toInt())
    println(3.99f.toDouble())
    println(300.0.toInt().toChar().code)
}
