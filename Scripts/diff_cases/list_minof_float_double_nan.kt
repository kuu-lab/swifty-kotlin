fun main() {
    val d = listOf(1.0, Double.NaN, 2.0)
    val dNaNLast = listOf(1.0, 2.0, Double.NaN)
    val f = listOf(1.0f, Float.NaN, 2.0f)
    println(d.maxOf { it })
    println(d.minOf { it })
    println(dNaNLast.maxOf { it })
    println(dNaNLast.minOf { it })
    println(d.maxOfOrNull { it })
    println(d.minOfOrNull { it })
    println(dNaNLast.maxOfOrNull { it })
    println(dNaNLast.minOfOrNull { it })
    println(f.maxOf { it })
    println(f.minOf { it })
    println(f.maxOfOrNull { it })
    println(f.minOfOrNull { it })
    println(listOf(-0.0, 0.0).maxOf { it })
    println(listOf(-0.0, 0.0).minOf { it })
    println(listOf(-0.0f, 0.0f).maxOf { it })
    println(listOf(-0.0f, 0.0f).minOf { it })
}
