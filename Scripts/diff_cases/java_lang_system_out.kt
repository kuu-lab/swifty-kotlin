fun main() {
    System.out.println("hello")
    System.out.println(42)
    System.out.println(42L)
    System.out.println(4.5)
    System.out.println(2.5f)
    System.out.println(true)
    System.out.println('Z')
    System.out.println(charArrayOf('a', 'b', 'c'))
    System.out.println(null as Any?)
    System.out.println()
    System.out.print("x")
    System.out.print(7)
    System.out.print(8L)
    System.out.print(1.5)
    System.out.print(false)
    System.out.print('Q')
    System.out.print(charArrayOf('x', 'y'))
    System.out.println()
    System.out.printf("n=%d s=%s%n", 1, "two")
    System.out.printf("%5d|%-5d|%05d%n", 42, 42, 42)
    System.out.printf("%.3f %e %g%n", 3.14159, 1234.5, 0.00001234)
    System.out.printf("%x %o %b %c%n", 255, 8, true, 'K')
    System.out.printf("%2\$s %1\$d%n", 7, "seven")
    System.out.printf("100%%%n")
    System.out.format("f=%d%n", 9)
    System.out.printf("%s", "chained").println()
    java.lang.System.out.println("qualified")
    val stream = System.out
    stream.printf("%s-%d%n", "var", 3)
    // PrintStream.close() marks the stream closed; subsequent writes are
    // silently dropped (kotlin.io.println bypasses System.out entirely —
    // KUU-4156).
    val wrapped = java.io.ByteArrayOutputStream()
    val wrappedStream = java.io.PrintStream(wrapped)
    wrappedStream.print("a")
    wrappedStream.close()
    wrappedStream.print("dropped")
    System.out.println(wrapped.toString())
    System.out.close()
    System.out.println("dropped-too")
}
