// KUU-3963: bound `::class` on stdlib-produced iterators reflects the JVM
// implementation class names (java.util.Arrays.ArrayItr, TreeMap.KeyIterator,
// JVM-anonymous iterators reporting null, ...), matching kotlinc.
fun n(k: kotlin.reflect.KClass<*>): String = "${k.simpleName}|${k.qualifiedName}"

fun main() {
    println(n(listOf(1).iterator()::class))
    println(n(listOf(1, 2).iterator()::class))
    println(n(listOf(1, 2).listIterator()::class))
    println(n(listOf(1, 2).listIterator(1)::class))
    println(n(listOf(1).listIterator()::class))
    println(n(arrayListOf(1, 2).iterator()::class))
    println(n(arrayListOf(1, 2).listIterator()::class))
    println(n(emptyList<Int>().iterator()::class))
    println(n(setOf(1, 2).iterator()::class))
    println(n(setOf(1).iterator()::class))
    println(n(emptySet<Int>().iterator()::class))
    println(n(mapOf(1 to "a", 2 to "b").entries.iterator()::class))
    println(n(mapOf(1 to "a").entries.iterator()::class))
    println(n(mapOf(1 to "a", 2 to "b").keys.iterator()::class))
    println(n(mapOf(1 to "a", 2 to "b").values.iterator()::class))
    println(n(listOf(1, 2).subList(0, 1).iterator()::class))
    println(n(listOf(1, 2).asReversed().iterator()::class))
    println(n(arrayOf(1, 2).asList().iterator()::class))
    println(n(arrayOf(1, 2).asList().listIterator()::class))
    println(n(intArrayOf(1, 2).asList().iterator()::class))
    println(n(intArrayOf(1, 2).asList().listIterator()::class))
    println(n(sortedSetOf(1, 2).iterator()::class))
    println(n(sortedMapOf(1 to "a", 2 to "b").keys.iterator()::class))
    println(n(sortedMapOf(1 to "a", 2 to "b").values.iterator()::class))
    println(n(sortedMapOf(1 to "a", 2 to "b").entries.iterator()::class))
    println(n(hashMapOf(1 to "a", 2 to "b").keys.iterator()::class))
    println(n(hashMapOf(1 to "a", 2 to "b").values.iterator()::class))
    println(n(hashMapOf(1 to "a", 2 to "b").entries.iterator()::class))
    println(n(hashSetOf(1, 2).iterator()::class))
    println(n(linkedSetOf(1, 2).iterator()::class))
    println(n(buildList { add(1); add(2) }.iterator()::class))
    println(n(buildSet { add(1); add(2) }.iterator()::class))
    println(n(buildMap { put(1, "a"); put(2, "b") }.keys.iterator()::class))
    println(n(buildMap { put(1, "a"); put(2, "b") }.values.iterator()::class))
    println(n(buildMap { put(1, "a"); put(2, "b") }.entries.iterator()::class))
    println(n(ArrayDeque(listOf(1, 2)).iterator()::class))
    println(n(ArrayDeque(listOf(1, 2)).listIterator()::class))
    println(n(listOf(1, 2).withIndex().iterator()::class))
    println(n((1..3).iterator()::class))
    println(n("ab".iterator()::class))
}
