// DIFF_JVM
private fun divisor(): Int { print("arg:"); return 3 }

fun main() {
    val negative = -7L
    val three = 3
    val absent: Long? = null
    val present: Long? = -7L
    println(negative.floorDiv(other = three))
    println(absent?.floorDiv(other = divisor()))
    println(present?.floorDiv(other = divisor()))
}
