// KUU-2029: preserve valid expected-type, explicit-type, and spread inference.
fun strings(): List<String> = listOf("a", "b")
fun emptyStrings(): List<String> = listOf()
fun explicitStrings(): List<String> = listOf<String>()
fun upcastStrings(): List<Any> = listOf<String>("x")
fun spreadStrings(xs: Array<String>): List<String> = listOf(*xs)
fun mixedStrings(xs: Array<String>): List<String> = listOf("a", *xs)
fun namedStrings(xs: Array<String>): List<String> = listOf(elements = xs)
fun <T> singleton(value: T): List<T> = listOf(value)

fun main() {
    println(strings())
    println(emptyStrings())
    println(explicitStrings())
    println(upcastStrings())
    val values = arrayOf("b", "c")
    println(spreadStrings(values))
    println(mixedStrings(values))
    println(namedStrings(values))
    val arrayElement: List<Array<String>> = listOf(element = values)
    println(arrayElement.size)
    println(arrayElement[0][0])
    println(singleton("ok"))
    val nullable: List<String?> = listOf(null, "x")
    println(nullable)
    val widened: List<Number> = listOf(1, 2)
    println(widened)
    val longs: List<Long> = listOf(1, -2)
    println(longs)
    val bytes: List<Byte> = listOf(1, -2)
    println(bytes)
    val shorts: List<Short> = listOf(1, -2)
    println(shorts)
    val unsigned: List<ULong> = listOf(1u, 2u)
    println(unsigned)
    val collection: Collection<Long> = listOf(1)
    println(collection)
    val iterable: Iterable<Byte> = listOf(1)
    println(iterable)
    val functions: List<(Int) -> Int> = listOf({ it + 1 }, { it * 2 })
    println(functions[0](3))
    println(functions[1](3))
}
