fun main() {
  val cps = listOf(
    0x41, 0x61, 0x01C5, 0x02B0, 0x4E2D, 0x2160, 0x3007,
    0x0669, 0x1D7D8,
    0x20AC, 0x00A2, 0x203F, 0x2040,
    0x30FB, 0x00B7, 0x0387,
    0x0300, 0x0903, 0x20DD,
    0x200C, 0x200D, 0x00AD,
    0x0001, 0x0009, 0x001F, 0x007F, 0x0085,
    0xD800, 0x10400, 0xFF21
  )
  for (cp in cps) {
    println(cp.toString(16) + " " +
      java.lang.Character.isJavaIdentifierStart(cp) + " " +
      java.lang.Character.isJavaIdentifierPart(cp))
  }
}
