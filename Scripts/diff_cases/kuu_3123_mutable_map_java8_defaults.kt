fun main() {
    val map = mutableMapOf("a" to 1)
    println(map.merge("a", 10) { old, new -> old + new })
    println(map.merge("b", 10) { old, new -> old + new })
    println(map.computeIfAbsent("c") { 3 })
    println(map.computeIfAbsent("a") { 99 })
    println(map.computeIfPresent("a") { _, value -> value + 1 })
    println(map.computeIfPresent("missing") { _, value -> value + 1 })
    println(map.putIfAbsent("a", 9))
    println(map.putIfAbsent("d", 4))
    println(map.getOrDefault("missing", 5))
    println(map.getOrDefault("a", 5))

    val nullable = mutableMapOf("null" to null, "old" to "value")
    println(nullable.getOrDefault("null", "fallback"))
    println(nullable.computeIfPresent("null") { _, _ -> "unexpected" })
    println(nullable.containsKey("null"))
    println(nullable.computeIfAbsent("null") { "created" })
    println(nullable.putIfAbsent("null", "ignored"))
    println(nullable.merge("null", "next") { _, _ -> null })
    println(nullable.containsKey("null"))
    println(nullable.computeIfPresent("old") { _, _ -> null })
    println(nullable.getOrDefault("old", "fallback"))
}
