// DIFF_JVM
fun main() {
    println(1.inc())
    println(1.dec())
    println(1L.inc())
    println(1L.dec())
    println(1.toByte().inc())
    println(1.toByte().dec())
    println(1.toShort().inc())
    println(1.toShort().dec())
    println(1.0f.inc())
    println(1.0f.dec())
    println(1.0.inc())
    println(1.0.dec())
    println(1u.inc())
    println(1u.dec())
    println(1uL.inc())
    println(1uL.dec())
    println(1.toUByte().inc())
    println(1.toUByte().dec())
    println(1.toUShort().inc())
    println(1.toUShort().dec())
    println('a'.inc())
    println('a'.dec())
}
