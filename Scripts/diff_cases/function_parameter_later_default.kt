// KUU-1954: Parenthesized callable arguments retain positional binding when a later callable defaults.
fun l(f: (String) -> String, g: (String) -> String = { it }) = f("x")
fun f(x: Int, g: (Int) -> Int = { it }): Int = g(x)
fun h(x: Int, g: (Int) -> Int = { it }, k: Int = 9): Int = g(x) + k
fun both(f: (String) -> String = { "f:$it" }, g: (String) -> String = { "g:$it" }) = f(g("x"))
fun shaped(f: (String) -> String = { it }, g: (Int) -> Int = { it }) = f("x") + ":" + g(1)
fun <T> generic(x: T, f: (T) -> String, g: (T) -> String = { "default" }) = f(x) + ":" + g(x)
class E(val x: Int, val g: (Int) -> Int = { it })
class J(val s: String, val f: (String) -> String, val k: Int = 0)
class K(val s: String, val g: (String) -> String = { it }, val f: (String) -> String)
class L(val f: (String) -> String, val g: (String) -> String = { it })
class M(val f: (String) -> String, val g: ((String) -> String)? = null)
class N(val xs: List<String>, val g: (String) -> String = { it })
class O(val xs: List<String>, val n: Int, val g: (String) -> String = { it })
class Choice<T>(val choices: List<T>, val toVariant: (String) -> T, val variantToString: (T) -> String = { "default" })
fun identity(s: String): String = s
fun main() {
    val fn: (String) -> String = { it + "!" }
    println(l(fn))
    println(l({ it + "!" }))
    println(l(::identity))
    println(l(f = fn))
    println(f(1))
    println(h(2))
    println(E(1).g(1))
    println(N(listOf("a")).g("a"))
    println(O(listOf("a"), 5).n)
    val j = J("a", fn)
    println(j.f(j.s) + ":" + j.k)
    val k = K("a", f = fn)
    println(k.f(k.g(k.s)))
    val trailing = K("a") { it + "!" }
    println(trailing.f(trailing.g(trailing.s)))
    val a = L(fn)
    println(a.f(a.g("x")))
    val b = L({ it + "!" })
    println(b.f(b.g("x")))
    val m = M(fn)
    println(m.f("x"))
    println(m.g == null)
    println(generic("x", fn))
    println(generic("x", { it + "!" }))
    println(generic<String>("x", fn))
    val choice = Choice(listOf("a"), { it + "!" })
    println(choice.toVariant(choice.choices[0]))
    println(choice.variantToString("a"))
    println(shaped({ it + "!" }))
    println(shaped { it + 1 })
    println(both(f = fn, fn))
    println(both(fn))
    println(both({ it + "!" }))
    println(both { it + "!" })
    println(both() { it + "!" })
    println(both label@ { it + "!" })
}
