fun main() {
    println(listOf(1, 2, 3).sum())
    println(listOf(1, 2, 3).average())
    println(emptyList<Int>().sum())
    println(emptyList<Int>().average().isNaN())
    println(listOf(2L, 4L, 6L).sum())
    println(listOf(2L, 4L, 6L).average())
    println(listOf(1.toByte(), 2.toByte()).sum())
    println(listOf(1.toShort(), 2.toShort()).sum())
    println(listOf(1.5f, 2.5f).sum())
    println(listOf(1.5f, 2.5f).average())
    println(listOf(1u, 2u, 3u).sum())
    println(listOf(1uL, 2uL, 3uL).sum())
    println(listOf(1u.toUByte(), 2u.toUByte()).sum())
    println(listOf(1u.toUShort(), 2u.toUShort()).sum())
    println(listOf(1.5, 2.5).first())
    println(listOf(1.5, 2.5).sum())
    val doubles: List<Double> = listOf(1.5, 2.5)
    val doubleSum: Double = doubles.sum()
    println(doubleSum)
    println(listOf(1.5, 2.5).average())
}
