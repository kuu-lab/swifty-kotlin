fun main() {
    println(listOf<Int>().javaClass)
    println(listOf(1).javaClass)
    println(listOf(1, 2).javaClass)
    println(setOf<Int>().javaClass)
    println(setOf(1).javaClass)
    println(setOf(1, 2).javaClass)
    println(mapOf<Int, String>().javaClass)
    println(mapOf(1 to "a").javaClass)
    println(mapOf(1 to "a", 2 to "b").javaClass)
    println(mutableListOf<Int>().javaClass)
    println(mutableListOf(1, 2).javaClass)
    println(mutableSetOf<Int>().javaClass)
    println(mutableMapOf<Int, String>().javaClass)
    println(emptyList<Int>().javaClass)
    println(emptySet<Int>().javaClass)
    println(emptyMap<Int, String>().javaClass)
    println(listOf(1, 2).size)
    println(setOf(1, 2).contains(2))
    println(mapOf(1 to "a")[1])
}
