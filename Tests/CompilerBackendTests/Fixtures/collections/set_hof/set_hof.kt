fun main() {
    val ints = setOf(3, 1, 4, 1, 5)
    val other = setOf(4, 5, 6)
    println(ints.map { it * 2 })
    println(ints.filter { it > 2 })
    println(ints.filterNot { it > 2 })
    println(ints.mapNotNull { if (it > 2) it else null })
    println(ints.flatMap { listOf(it, it * 10) })
    var first = true
    ints.forEach { if (!first) print(" "); first = false; print(it) }
    println()
    println(ints.count { it > 2 })
    println("${ints.any { it > 4 }} ${ints.all { it > 0 }} ${ints.none { it > 9 }}")
    println("${ints.first()} ${ints.firstOrNull()} ${ints.last()} ${ints.lastOrNull()}")
    println("${ints.singleOrNull()} ${setOf(9).singleOrNull()}")
    println("${ints.containsAll(listOf(1, 3))} ${ints.containsAll(listOf(1, 9))} ${ints.isEmpty()}")
    println(ints.intersect(other))
    println(ints.union(other))
    println(ints.subtract(other))
    println(ints.sorted())
    println(ints.sortedDescending())
    println("${ints.maxOrNull()} ${ints.minOrNull()}")
    println(ints.toList())
    println(ints.toMutableList())
    println(ints.toSet())
    println(ints.toMutableSet())

    val words = setOf("beta", "alpha", "beta", "gamma")
    println(words.intersect(setOf("gamma", "beta")))
    println(words.union(listOf("delta", "alpha")))
    println(words.subtract(listOf("beta")))
    println(words.sorted())
    println(words.sortedDescending())
    println("${words.maxOrNull()} ${words.minOrNull()}")
    println("${words.size} ${words.contains("alpha")} $words")
}
