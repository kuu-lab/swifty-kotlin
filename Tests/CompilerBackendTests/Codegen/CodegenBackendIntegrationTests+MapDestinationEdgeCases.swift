        try assertKotlinOutput(
            source,
            moduleName: "MapKeysToDestination",
            expected:
                """
                zero
                zero
                one
                two
                3
                """ + "\n"
        )
    }

    @Test
    func testCodegenMapValuesToUsesCanonicalDiffCase() throws {
        let root = URL(fileURLWithPath: #filePath)
