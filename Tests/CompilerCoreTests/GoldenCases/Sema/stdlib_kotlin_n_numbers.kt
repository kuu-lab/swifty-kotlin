package golden.sema

fun main() {
    val doubleValue = 3.99
    println(doubleValue.toInt())
    println(doubleValue.toLong())
    println(doubleValue.toChar())

    val floatValue = 2.5f
    println(floatValue.toInt())
    println(floatValue.toLong())
    println(floatValue.toDouble())
    println(floatValue.toChar())
}
