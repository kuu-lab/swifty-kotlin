package java.time

import kotlin.math.abs as kotlinAbs

/**
 * A time-zone offset from Greenwich/UTC, such as {@code +02:00}.
 * The maximum supported range is from -18:00 to +18:00 inclusive.
 */
public class ZoneOffset private constructor(
    public val totalSeconds: Int,
) : ZoneId(), Comparable<ZoneOffset> {
    override val id: String = javaTimeZoneOffsetId(totalSeconds)

    public fun getTotalSeconds(): Int = totalSeconds

    override fun javaTimeOffsetAt(epochSecond: Long): ZoneOffset = this

    override fun normalized(): ZoneOffset = this

    override fun compareTo(other: ZoneOffset): Int = other.totalSeconds - totalSeconds

    override fun equals(other: Any?): Boolean = other is ZoneOffset && totalSeconds == other.totalSeconds

    override fun hashCode(): Int = totalSeconds

    override fun toString(): String = id

    public companion object {
        /** The time-zone offset for UTC, with an ID of 'Z'. */
        public val UTC: ZoneOffset = ZoneOffset(0)

        /** Constant for the minimum supported offset, {@code -18:00}. */
        public val MIN: ZoneOffset = ZoneOffset(-javaTimeZoneOffsetMaxSeconds)

        /** Constant for the maximum supported offset, {@code +18:00}. */
        public val MAX: ZoneOffset = ZoneOffset(javaTimeZoneOffsetMaxSeconds)

        /**
         * Obtains an instance of [ZoneOffset] using the ID. Accepts the formats
         * generated by [id], plus {@code Z}, {@code +h}, {@code +hh}, {@code +hhmm},
         * {@code +hh:mm}, {@code +hhmmss} and {@code +hh:mm:ss}.
         */
        public fun of(offsetId: String): ZoneOffset {
            if (offsetId == "Z") {
                return UTC
            }
            var id = offsetId
            val hours: Int
            val minutes: Int
            val seconds: Int
            when (id.length) {
                2 -> {
                    id = id.substring(0, 1) + "0" + id.substring(1)
                    hours = javaTimeZoneOffsetParseNumber(id, 1, false)
                    minutes = 0
                    seconds = 0
                }
                3 -> {
                    hours = javaTimeZoneOffsetParseNumber(id, 1, false)
                    minutes = 0
                    seconds = 0
                }
                5 -> {
                    hours = javaTimeZoneOffsetParseNumber(id, 1, false)
                    minutes = javaTimeZoneOffsetParseNumber(id, 3, false)
                    seconds = 0
                }
                6 -> {
                    hours = javaTimeZoneOffsetParseNumber(id, 1, false)
                    minutes = javaTimeZoneOffsetParseNumber(id, 4, true)
                    seconds = 0
                }
                7 -> {
                    hours = javaTimeZoneOffsetParseNumber(id, 1, false)
                    minutes = javaTimeZoneOffsetParseNumber(id, 3, false)
                    seconds = javaTimeZoneOffsetParseNumber(id, 5, false)
                }
                9 -> {
                    hours = javaTimeZoneOffsetParseNumber(id, 1, false)
                    minutes = javaTimeZoneOffsetParseNumber(id, 4, true)
                    seconds = javaTimeZoneOffsetParseNumber(id, 7, true)
                }
                else -> throw DateTimeException("Invalid ID for ZoneOffset, invalid format: " + id)
            }
            val first = id[0]
            if (first != '+' && first != '-') {
                throw DateTimeException("Invalid ID for ZoneOffset, plus/minus not found when expected: " + id)
            }
            return if (first == '-') {
                ofHoursMinutesSeconds(-hours, -minutes, -seconds)
            } else {
                ofHoursMinutesSeconds(hours, minutes, seconds)
            }
        }

        /** Obtains an instance of [ZoneOffset] using an offset in hours, from -18 to +18. */
        public fun ofHours(hours: Int): ZoneOffset = ofHoursMinutesSeconds(hours, 0, 0)

        /**
         * Obtains an instance of [ZoneOffset] using an offset in hours and minutes.
         * The sign of the hours and minutes components must match.
         */
        public fun ofHoursMinutes(hours: Int, minutes: Int): ZoneOffset = ofHoursMinutesSeconds(hours, minutes, 0)

        /**
         * Obtains an instance of [ZoneOffset] using an offset in hours, minutes and
         * seconds. The sign of all three components must match.
         */
        public fun ofHoursMinutesSeconds(hours: Int, minutes: Int, seconds: Int): ZoneOffset {
            javaTimeValidateZoneOffset(hours, minutes, seconds)
            return ofTotalSeconds(hours * 3_600 + minutes * 60 + seconds)
        }

        /** Obtains an instance of [ZoneOffset] from a total offset in seconds, from -64800 to +64800. */
        public fun ofTotalSeconds(totalSeconds: Int): ZoneOffset {
            if (totalSeconds < -javaTimeZoneOffsetMaxSeconds || totalSeconds > javaTimeZoneOffsetMaxSeconds) {
                throw DateTimeException("Zone offset not in valid range: -18:00 to +18:00")
            }
            return ZoneOffset(totalSeconds)
        }
    }
}

private const val javaTimeZoneOffsetMaxSeconds: Int = 18 * 3_600

private fun javaTimeZoneOffsetId(totalSeconds: Int): String {
    if (totalSeconds == 0) {
        return "Z"
    }
    val absTotalSeconds = kotlinAbs(totalSeconds)
    val absHours = absTotalSeconds / 3_600
    val absMinutes = (absTotalSeconds / 60) % 60
    val absSeconds = absTotalSeconds % 60
    val builder = StringBuilder()
    builder.append(if (totalSeconds < 0) "-" else "+")
    if (absHours < 10) builder.append('0')
    builder.append(absHours)
    builder.append(':')
    if (absMinutes < 10) builder.append('0')
    builder.append(absMinutes)
    if (absSeconds != 0) {
        builder.append(':')
        if (absSeconds < 10) builder.append('0')
        builder.append(absSeconds)
    }
    return builder.toString()
}

private fun javaTimeZoneOffsetParseNumber(offsetId: String, pos: Int, precededByColon: Boolean): Int {
    if (precededByColon && offsetId[pos - 1] != ':') {
        throw DateTimeException("Invalid ID for ZoneOffset, colon not found when expected: " + offsetId)
    }
    val ch1 = offsetId[pos]
    val ch2 = offsetId[pos + 1]
    if (ch1 < '0' || ch1 > '9' || ch2 < '0' || ch2 > '9') {
        throw DateTimeException("Invalid ID for ZoneOffset, non numeric characters found: " + offsetId)
    }
    return (ch1 - '0') * 10 + (ch2 - '0')
}

private fun javaTimeValidateZoneOffset(hours: Int, minutes: Int, seconds: Int) {
    if (hours < -18 || hours > 18) {
        throw DateTimeException(
            "Zone offset hours not in valid range: value " + hours + " is not in the range -18 to 18"
        )
    }
    if (hours > 0) {
        if (minutes < 0 || seconds < 0) {
            throw DateTimeException("Zone offset minutes and seconds must be positive because hours is positive")
        }
    } else if (hours < 0) {
        if (minutes > 0 || seconds > 0) {
            throw DateTimeException("Zone offset minutes and seconds must be negative because hours is negative")
        }
    } else if ((minutes > 0 && seconds < 0) || (minutes < 0 && seconds > 0)) {
        throw DateTimeException("Zone offset minutes and seconds must have the same sign")
    }
    if (minutes < -59 || minutes > 59) {
        throw DateTimeException(
            "Zone offset minutes not in valid range: value " + minutes + " is not in the range -59 to 59"
        )
    }
    if (seconds < -59 || seconds > 59) {
        throw DateTimeException(
            "Zone offset seconds not in valid range: value " + seconds + " is not in the range -59 to 59"
        )
    }
    if (kotlinAbs(hours) == 18 && (minutes != 0 || seconds != 0)) {
        throw DateTimeException("Zone offset not in valid range: -18:00 to +18:00")
    }
}
